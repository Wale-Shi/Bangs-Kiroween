import ImageIO
import SwiftUI
import UniformTypeIdentifiers

/// One thing you copied.
struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, link, code, color, image, file }

    var id = UUID()
    var kind: Kind
    /// The text; the paths for files, one per line; a description for images.
    var text: String
    /// RTF and HTML as copied, so formatted text pastes back formatted.
    var rich: [String: Data]?
    /// The image's file under Clipboard/, and its size in pixels.
    var image: String?
    var size: [Int]?
    var app: String?
    var date = Date()
    var pinned = false
    /// Identical copies collapse into one item.
    var key: String

    var files: [URL] { kind == .file ? text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : [] }
}

/// Clipboard history: watches the pasteboard, keeps what you copy and puts it back when you pick it.
@MainActor
final class ClipboardHistory: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0

    let preferences: Preferences
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    /// Our own writes are not new copies.
    private var ownChange = -1
    /// Bangs is using the pasteboard for a moment (a ⌘C to read a selection, then putting back what was there): nothing
    /// that changes on it meanwhile is a copy of yours, nor is putting it back.
    var borrowed = false {
        didSet {
            guard !borrowed else { return }
            lastChange = pasteboard.changeCount
            ownChange = lastChange
        }
    }
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private var subscriptions: Set<AnyCancellable> = []
    let images = Storage.directory("Clipboard")

    /// Password managers mark secrets with these (nspasteboard.org); such copies are never kept.
    private static let secret: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]
    private static let richTypes: [NSPasteboard.PasteboardType] = [.rtf, .html]

    /// `pasteboard` is the system's; tests give one of their own.
    init(preferences: Preferences, pasteboard: NSPasteboard = .general) {
        self.preferences = preferences
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
        items = Storage.load([ClipItem].self, from: "clipboard.json") ?? []
        prune()
        // A smaller limit applies at once, not at the next copy.
        preferences.$clipboardLimit.combineLatest(preferences.$clipboardDays).dropFirst().sink { [weak self] _ in
            DispatchQueue.main.async {
                guard let self else { return }
                let before = self.items.count
                self.prune()
                if self.items.count != before { self.save() }
            }
        }.store(in: &subscriptions)
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
        timer?.tolerance = 0.1
    }

    /// Pinned first, then the most recent; filtered by the search.
    var visible: [ClipItem] {
        let words = query.lowercased().split(separator: " ")
        let matching = words.isEmpty ? items : items.filter { item in
            let haystack = "\(item.text) \(item.app ?? "")".lowercased()
            return words.allSatisfy { haystack.contains($0) }
        }
        return matching.filter(\.pinned) + matching.filter { !$0.pinned }
    }

    var selected: ClipItem? {
        let visible = visible
        return visible.indices.contains(selection) ? visible[selection] : nil
    }

    // MARK: Watching

    func poll() {
        guard !borrowed else { return }
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard change != ownChange else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.secret) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        if let item = read(app: app) { add(item) }
    }

    private func read(app: String?) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ClipItem(kind: .file, text: paths, app: app, key: "file:\(paths)")
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var rich: [String: Data] = [:]
            for type in Self.richTypes {
                if let data = pasteboard.data(forType: type), data.count < 512 * 1024 { rich[type.rawValue] = data }
            }
            return ClipItem(kind: Self.kind(of: string), text: string, rich: rich.isEmpty ? nil : rich, app: app, key: "text:\(string)")
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), let item = imageItem(data, app: app) {
            return item
        }
        return nil
    }

    /// An image copied in another app. Its size comes from the header; a PNG is kept as it is, anything else becomes one
    /// off the main thread (decoding and encoding a large screenshot here froze the island for up to a second).
    private func imageItem(_ data: Data, app: String?) -> ClipItem? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int else { return nil }
        let hash = SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
        let name = "\(hash).png"
        let url = images.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) {
            let png = (CGImageSourceGetType(source) as String?) == UTType.png.identifier
            Self.disk.async { [weak self] in
                guard let file = png ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { return }
                try? file.write(to: url)
                // The row drew its icon while the file was being written: now it can show the picture.
                DispatchQueue.main.async { self?.objectWillChange.send() }
            }
        }
        return ClipItem(kind: .image, text: "图片 \(width)×\(height)", image: name, size: [width, height], app: app, key: "image:\(hash)")
    }

    /// Writing the history and its images, in order, off the main thread.
    private static let disk = DispatchQueue(label: "bangs.clipboard", qos: .utility)

    static func kind(of string: String) -> ClipItem.Kind {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.range(of: #"^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$|^rgba?\([\d\s.,%]+\)$"#, options: .regularExpression) != nil { return .color }
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), let scheme = url.scheme, ["http", "https", "ftp", "mailto"].contains(scheme) { return .link }
        let lines = trimmed.split(separator: "\n", omittingEmptySubsequences: false)
        let codeish = trimmed.range(of: #"[{};]\s*$|^\s{2,}\S|=>|->|\bfunc\b|\bfunction\b|\bdef\b|\bimport\b|\breturn\b|</\w+>"#, options: [.regularExpression]) != nil
        return lines.count > 1 && codeish ? .code : .text
    }

    // MARK: Changing

    /// Records something copied, or brings an identical earlier copy back to the top.
    func add(_ item: ClipItem) {
        var item = item
        if let index = items.firstIndex(where: { $0.key == item.key }) {
            item.id = items[index].id
            item.pinned = items[index].pinned
            items.remove(at: index)
        }
        items.insert(item, at: 0)
        prune()
        save()
    }

    /// An image Bangs made itself (a screenshot): recorded and put on the pasteboard.
    /// The file is a PNG already: it is kept as it is, its size read from its header, never decoded and encoded again
    /// (seconds, for a long scrolling screenshot).
    func addImage(at url: URL) {
        guard let data = try? Data(contentsOf: url), let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int else { return }
        let hash = SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
        let name = "\(hash).png"
        let copy = images.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: copy.path) { try? data.write(to: copy) }
        let item = ClipItem(kind: .image, text: "图片 \(width)×\(height)", image: name, size: [width, height], app: "截图", key: "image:\(hash)")
        add(item)
        write(items.first { $0.key == item.key } ?? item)
    }

    /// Text Bangs made (read off the screen, or transformed): recorded and put on the pasteboard.
    /// `rich`: other forms of the same text by pasteboard type (HTML for a table), for apps that take them.
    func copy(_ text: String, app: String, rich: [String: Data]? = nil) {
        let item = ClipItem(kind: Self.kind(of: text), text: text, rich: rich, app: app, key: "text:\(text)")
        add(item)
        write(items.first { $0.key == item.key } ?? item)
    }

    /// Text on the pasteboard only, not in the history.
    func copyOnly(_ text: String) {
        write(ClipItem(kind: .text, text: text, key: ""))
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeOrphans()
        save()
    }

    func clear() {
        items.removeAll { !$0.pinned }
        removeOrphans()
        save()
    }

    /// Puts an item back on the pasteboard, and at the top of the history.
    func write(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .file:
            pasteboard.writeObjects(item.files as [NSURL])
        case .image:
            if let name = item.image, let data = try? Data(contentsOf: images.appendingPathComponent(name)) {
                pasteboard.setData(data, forType: .png)
                // TIFF too, for the few apps that read only that; not for a huge image, where it would be hundreds of
                // megabytes uncompressed.
                let pixels = (item.size?.first ?? 0) * (item.size?.last ?? 0)
                if pixels <= 16_000_000, let tiff = NSImage(data: data)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
            }
        default:
            pasteboard.setString(item.text, forType: .string)
            for (type, data) in item.rich ?? [:] { pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type)) }
        }
        ownChange = pasteboard.changeCount
        lastChange = ownChange
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// Presses ⌘V in the app in front. Needs Accessibility; returns false (after asking once) without it.
    static func pasteIntoFrontApp() -> Bool {
        guard AXIsProcessTrusted() else {
            AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
            return false
        }
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
        return true
    }

    private func prune() {
        let cutoff = preferences.clipboardDays > 0 ? Date().addingTimeInterval(-Double(preferences.clipboardDays) * 86400) : .distantPast
        var kept = 0
        items = items.filter { item in
            if item.pinned { return true }
            guard item.date >= cutoff, kept < preferences.clipboardLimit else { return false }
            kept += 1
            return true
        }
        removeOrphans()
    }

    private func removeOrphans() {
        let used = Set(items.compactMap(\.image)), images = images
        Self.disk.async {
            for name in (try? FileManager.default.contentsOfDirectory(atPath: images.path)) ?? [] where !used.contains(name) {
                try? FileManager.default.removeItem(at: images.appendingPathComponent(name))
            }
        }
    }

    private func save() {
        saveWork?.cancel()
        let snapshot = items
        let work = DispatchWorkItem { Self.disk.async { Storage.save(snapshot, to: "clipboard.json") } }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    // MARK: Keyboard

    enum KeyResult { case ignored, handled, paste(ClipItem, copyOnly: Bool) }

    /// ↑↓ choose, return pastes, ⌘return copies, ⌘1–9 pastes that item, ⌘P pins, ⌘⌫ deletes.
    func handle(_ event: NSEvent) -> KeyResult {
        let count = visible.count
        let command = event.modifierFlags.contains(.command)
        switch event.keyCode {
        case 125: if count > 0 { selection = (selection + 1) % count }; return .handled
        case 126: if count > 0 { selection = (selection - 1 + count) % count }; return .handled
        case 36, 76: return selected.map { .paste($0, copyOnly: command) } ?? .handled
        case 51 where command: if let item = selected { delete(item) }; return .handled
        case 35 where command: if let item = selected { togglePin(item) }; return .handled
        default:
            if command, let digit = Int(event.charactersIgnoringModifiers ?? ""), (1...9).contains(digit), visible.count >= digit {
                return .paste(visible[digit - 1], copyOnly: false)
            }
            return .ignored
        }
    }
}

// MARK: Views

struct ClipboardView: View {
    @ObservedObject var history: ClipboardHistory
    let pick: (ClipItem, Bool) -> Void
    @FocusState private var searching: Bool
    /// The transform just applied, for a moment's confirmation.
    @State private var applied: String?
    static let rowHeight: CGFloat = 40

    var body: some View {
        let visible = history.visible
        VStack(alignment: .leading, spacing: 6) {
            HStack(spacing: 6) {
                Image(systemName: "magnifyingglass").font(.system(size: 11, weight: .medium)).foregroundStyle(Palette.dim)
                TextField("", text: $history.query, prompt: Text("搜索剪贴板，直接打字即可").foregroundColor(Palette.dim))
                    .textFieldStyle(.plain)
                    .font(.system(size: 12.5))
                    .foregroundStyle(Palette.ink)
                    .focused($searching)
                if !history.query.isEmpty {
                    Button { history.query = "" } label: { Image(systemName: "xmark.circle.fill").foregroundStyle(Palette.dim) }.buttonStyle(.plain)
                }
            }
            .fieldChrome(focused: false)

            if visible.isEmpty {
                Text(history.query.isEmpty ? "复制的文字、链接、图片和文件会出现在这里。" : "没有匹配的内容")
                    .font(.system(size: 12)).foregroundStyle(Palette.muted).padding(.vertical, 14)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 1) {
                            ForEach(Array(visible.enumerated()), id: \.element.id) { index, item in
                                if index == 0 && item.pinned { section("置顶") }
                                if !item.pinned && (index == 0 || visible[index - 1].pinned) { section("最近") }
                                ClipRow(item: item, index: index, selected: index == history.selection, history: history,
                                        offers: offers(for: item), apply: apply)
                                    .id(item.id)
                                    .onTapGesture { pick(item, false) }
                            }
                        }
                        .padding(.vertical, 6)
                    }
                    .scrollIndicators(.never)
                    .frame(height: min(CGFloat(visible.count) * (Self.rowHeight + 1) + 52, 8.5 * Self.rowHeight))
                    // Rows fade out at the edges instead of being cut off.
                    .mask(LinearGradient(stops: [.init(color: .clear, location: 0), .init(color: .black, location: 0.04),
                                                 .init(color: .black, location: 0.92), .init(color: .clear, location: 1)],
                                         startPoint: .top, endPoint: .bottom))
                    .onChange(of: history.selection) { _, selection in
                        if visible.indices.contains(selection) { proxy.scrollTo(visible[selection].id) }
                    }
                }
            }
            if let item = history.selected, case let offers = offers(for: item), !offers.isEmpty {
                HStack(spacing: 6) {
                    Text(applied.map { "已复制「\($0)」的结果" } ?? "转换").font(.system(size: 10.5)).foregroundStyle(applied == nil ? Palette.dim : Palette.ok)
                        .lineLimit(1)
                    ForEach(offers.prefix(4)) { offer in
                        Button { apply(offer) } label: {
                            Text(offer.title).font(.system(size: 11)).foregroundStyle(Palette.ink).lineLimit(1).truncationMode(.tail)
                                .padding(.horizontal, 8).padding(.vertical, 3)
                                .background(Capsule().fill(Palette.wash(0.08)))
                                .overlay(Capsule().strokeBorder(Palette.accent.opacity(0.55), lineWidth: 0.75))
                        }
                        .buttonStyle(.plain)
                        .help(SessionStore.oneLine(offer.result, limit: 200))
                    }
                    Spacer(minLength: 0)
                }
                .padding(.horizontal, 4)
            }
            HStack(spacing: 14) {
                KeyHint(keys: [.returnKey], title: "粘贴")
                KeyHint(keys: [.text("⌘"), .returnKey], title: "只复制")
                KeyHint(keys: [.text("⌘"), .text("P")], title: "置顶")
                KeyHint(keys: [.text("⌘"), .text("⌫")], title: "删除")
            }
            .frame(maxWidth: .infinity)
            .padding(.top, 2)
        }
        .onChange(of: history.selection) { _, _ in applied = nil }
        .onAppear {
            history.selection = 0
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { searching = true }
        }
    }

    /// Conversions for an item's text, when they are turned on and it is text.
    private func offers(for item: ClipItem) -> [Transform.Offer] {
        let preferences = history.preferences
        guard preferences.transforms, [.text, .code, .link].contains(item.kind) else { return [] }
        return Transform.offers(for: item.text, kinds: preferences.transformKinds, utc: preferences.transformsInUTC)
    }

    /// Copies the result; kept in the history as a new item unless you chose otherwise. The original stays as it was.
    private func apply(_ offer: Transform.Offer) {
        if history.preferences.transformKeepsResult {
            history.copy(offer.result, app: "转换")
            history.selection = history.visible.firstIndex { $0.text == offer.result } ?? 0
        } else {
            history.copyOnly(offer.result)
        }
        applied = offer.title
    }

    private func section(_ title: String) -> some View {
        Text(title).font(.system(size: 10.5, weight: .medium)).foregroundStyle(Palette.dim).frame(maxWidth: .infinity, alignment: .leading)
            .padding(.leading, 8).padding(.top, 6).padding(.bottom, 3)
    }
}

struct ClipRow: View {
    let item: ClipItem
    let index: Int
    let selected: Bool
    @ObservedObject var history: ClipboardHistory
    var offers: [Transform.Offer] = []
    var apply: (Transform.Offer) -> Void = { _ in }
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 10) {
            icon.frame(width: 28, height: 28)
            VStack(alignment: .leading, spacing: 1) {
                Text(title).font(.system(size: 12.5, design: item.kind == .code ? .monospaced : .default)).foregroundStyle(Palette.ink).lineLimit(1).truncationMode(.middle)
                Text(subtitle).font(.system(size: 10.5)).foregroundStyle(Palette.muted).lineLimit(1)
            }
            Spacer(minLength: 6)
            if hovering || item.pinned {
                Button { history.togglePin(item) } label: {
                    Image(systemName: item.pinned ? "pin.fill" : "pin").font(.system(size: 11)).foregroundStyle(item.pinned ? Palette.warn : Palette.muted)
                }
                .buttonStyle(.plain)
                .help(item.pinned ? "取消置顶" : "置顶")
            }
            if hovering {
                Button { history.delete(item) } label: { Image(systemName: "trash").font(.system(size: 11)).foregroundStyle(Palette.muted) }
                    .buttonStyle(.plain)
                    .help("删除")
            }
            if index < 9 && !hovering {
                Text("⌘\(index + 1)").font(.system(size: 10, weight: .medium)).foregroundStyle(selected ? Palette.muted : Palette.dim)
            }
        }
        .padding(.horizontal, 8)
        .frame(height: ClipboardView.rowHeight)
        .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(selected ? Palette.accent.opacity(0.18) : hovering ? Palette.row : .clear))
        .contentShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
        .onHover { hovering = $0 }
        .contextMenu {
            Button(item.pinned ? "取消置顶" : "置顶") { history.togglePin(item) }
            SendToAgentMenu { payload }
            if !offers.isEmpty {
                Section("转换并复制") {
                    ForEach(offers) { offer in Button(offer.title) { apply(offer) } }
                }
            }
            Divider()
            Button("删除") { history.delete(item) }
        }
    }

    /// What an agent gets: the files' paths, the image as a file, else the text.
    private var payload: Handoff.Payload {
        switch item.kind {
        case .file: .files(item.files)
        case .image: item.image.map { .files([history.images.appendingPathComponent($0)]) } ?? .text(item.text)
        default: .text(item.text)
        }
    }

    private var title: String {
        switch item.kind {
        case .file:
            let files = item.files
            return files.count == 1 ? files[0].lastPathComponent : "\(files[0].lastPathComponent) 等 \(files.count) 个文件"
        default:
            return SessionStore.oneLine(item.text, limit: 160)
        }
    }

    private var subtitle: String {
        var parts = [item.app ?? "未知来源"]
        switch item.kind {
        case .code: parts.append("代码 · \(item.text.split(separator: "\n").count) 行")
        case .link: parts.append("链接")
        case .color: parts.append("颜色")
        case .file: parts.append(item.files.count == 1 ? (item.files[0].deletingLastPathComponent().path as NSString).abbreviatingWithTildeInPath : "文件")
        case .image: if let size = item.size, size.count == 2 { parts.append("\(size[0])×\(size[1])") }
        case .text: if item.text.count > 160 { parts.append("\(item.text.count) 字") }
        }
        if item.pinned {
            parts.append("置顶")
        } else {
            parts.append(Date().timeIntervalSince(item.date) < 60 ? "刚刚" : Self.relative.localizedString(for: item.date, relativeTo: Date()))
        }
        return parts.joined(separator: " · ")
    }

    private static let relative: RelativeDateTimeFormatter = {
        let formatter = RelativeDateTimeFormatter()
        formatter.locale = Locale(identifier: "zh_CN")
        formatter.unitsStyle = .short
        return formatter
    }()

    @ViewBuilder private var icon: some View {
        switch item.kind {
        case .image:
            if let name = item.image, let image = Thumbnails.image(at: history.images.appendingPathComponent(name), points: 28) {
                Image(nsImage: image).resizable().aspectRatio(contentMode: .fill).frame(width: 28, height: 28)
                    .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
                    .overlay(RoundedRectangle(cornerRadius: 6, style: .continuous).strokeBorder(Palette.wash(0.12), lineWidth: 0.5))
            } else { tile("photo") }
        case .color:
            RoundedRectangle(cornerRadius: 6, style: .continuous).fill(Self.color(item.text) ?? Palette.row)
                .overlay(RoundedRectangle(cornerRadius: 6, style: .continuous).stroke(Palette.wash(0.15)))
        case .file:
            Image(nsImage: Thumbnails.icon(for: item.files.first ?? URL(fileURLWithPath: "/"))).resizable().frame(width: 24, height: 24)
        case .link: tile("link")
        case .code: tile("chevron.left.forwardslash.chevron.right")
        case .text: tile("text.alignleft")
        }
    }

    private func tile(_ symbol: String) -> some View {
        RoundedRectangle(cornerRadius: 6, style: .continuous).fill(Palette.wash(0.06))
            .overlay(RoundedRectangle(cornerRadius: 6, style: .continuous).strokeBorder(Palette.wash(0.08), lineWidth: 0.5))
            .overlay(Image(systemName: symbol).font(.system(size: 11)).foregroundStyle(Palette.muted))
    }

    static func color(_ text: String) -> Color? {
        let hex = text.trimmingCharacters(in: .whitespacesAndNewlines).dropFirst()
        guard text.hasPrefix("#") || text.trimmingCharacters(in: .whitespaces).hasPrefix("#") else { return nil }
        let full = hex.count == 3 ? hex.map { "\($0)\($0)" }.joined() : String(hex.prefix(6))
        guard let value = UInt32(full, radix: 16) else { return nil }
        return Color(red: Double(value >> 16 & 0xFF) / 255, green: Double(value >> 8 & 0xFF) / 255, blue: Double(value & 0xFF) / 255)
    }
